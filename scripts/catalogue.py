#!/usr/bin/env python3
"""Catalogue of the result sets under experiments/ and the papers they serve.

The results stay where the tools wrote them, because campaign.py, the av2 and
av3 mirrors and the papers' import scripts all find them by path. The
catalogue, ``experiments/catalogue.toml``, says what each set is: which paper
uses it, for which question, whether that paper's numbers come from it, and
what replaced it if it was superseded.

    catalogue.py check      every entry of experiments/ is catalogued, and every
                            catalogued path that should be here is
    catalogue.py render     rewrite experiments/CATALOGUE.md from the TOML
    catalogue.py list [--paper P] [--status S]
                            one line per set, for a quick look

``check`` reads only the catalogue when experiments/ holds no results, as in CI
or a fresh clone, so it validates the file without the data.
"""

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
EXPERIMENTS = REPO / "experiments"
CATALOGUE = EXPERIMENTS / "catalogue.toml"
RENDERED = EXPERIMENTS / "CATALOGUE.md"

PAPERS = ("ext", "tlsf", "none")
STATUSES = ("cited", "supporting", "superseded", "pilot", "development",
            "inputs")
REQUIRED = ("name", "paths", "paper", "status", "purpose")
# Entries that are tooling state, not results.
INFRA = {".merge_tmp", "queue", "compare-manifests", "catalogue.toml",
         "CATALOGUE.md"}


def load(path=CATALOGUE):
    with open(path, "rb") as fh:
        data = tomllib.load(fh)
    return data.get("paper", {}), data.get("set", [])


def validate(papers, sets):
    errors = []
    names = set()
    owners = {}
    for i, s in enumerate(sets):
        label = s.get("name", f"set #{i}")
        for key in REQUIRED:
            if key not in s:
                errors.append(f"{label}: missing {key}")
        if label in names:
            errors.append(f"{label}: duplicate name")
        names.add(label)
        if s.get("paper") not in PAPERS:
            errors.append(f"{label}: paper {s.get('paper')!r} not in {PAPERS}")
        if s.get("status") not in STATUSES:
            errors.append(f"{label}: status {s.get('status')!r} not in {STATUSES}")
        if s.get("status") == "superseded" and not s.get("superseded_by"):
            errors.append(f"{label}: superseded without superseded_by")
        if s.get("paper") != "none" and s.get("paper") not in papers:
            errors.append(f"{label}: paper {s.get('paper')!r} has no [paper] table")
        if "location" not in s:
            for p in s.get("paths", []):
                if p in owners:
                    errors.append(f"{p}: claimed by {owners[p]} and {label}")
                owners[p] = label
    for s in sets:
        for ref in [s.get("superseded_by")] if s.get("superseded_by") else []:
            if ref not in names:
                errors.append(f"{s['name']}: superseded_by {ref!r} is not a set")
    return errors, owners


def present(root):
    return {p.name for p in root.iterdir()} - INFRA if root.is_dir() else set()


def check(papers, sets, root=EXPERIMENTS):
    errors, owners = validate(papers, sets)
    here = present(root)
    # Results are untracked, so a clone without them holds only the dated
    # campaign directories; check the data only where some of it is present.
    has_results = any(not name.startswith("20") for name in here)
    if has_results:
        for name in sorted(here - set(owners)):
            errors.append(f"{name}: in experiments/ but not catalogued")
        for p, label in sorted(owners.items()):
            s = next(x for x in sets if x["name"] == label)
            if p not in here and not s.get("absent_ok"):
                errors.append(f"{p}: catalogued under {label} but missing "
                              "(set absent_ok if it lives only on a host)")
    for s in sets:
        loc = s.get("location")
        if loc:
            base = Path(loc).expanduser()
            if base.is_dir():
                for p in s["paths"]:
                    if not (base / p).exists():
                        errors.append(f"{s['name']}: {base / p} missing")
    return errors


def size_of(s):
    return s.get("size", "")


def render(papers, sets):
    out = ["# Experiment catalogue", "",
           "Generated by `scripts/catalogue.py render` from `catalogue.toml`; edit that file, not this one.",
           "",
           "Each set stays at the path its tools wrote, under this checkout's `experiments/` unless *Location* names another checkout. *Status* is `cited` when the paper's numbers or figures come from the set, `supporting` when the paper's design or text relies on it without reporting it, `superseded` when a later set replaced it, `pilot` for a timing or design pilot, `development` for engine tuning no paper reports, and `inputs` for configs and reference data.",
           ""]
    order = [k for k in papers] + ["none"]
    for key in order:
        group = [s for s in sets if s["paper"] == key]
        if not group:
            continue
        if key == "none":
            out += ["## Not used by a paper", ""]
        else:
            p = papers[key]
            out += [f"## {p['title']}", "", f"Repository: `{p['repo']}`. {p.get('note', '')}".rstrip(), ""]
        for status in STATUSES:
            rows = [s for s in group if s["status"] == status]
            if not rows:
                continue
            out += [f"### {status.capitalize()}", "",
                    "| Set | Date | Question | Purpose | Campaign | Location | Notes |",
                    "|---|---|---|---|---|---|---|"]
            for s in sorted(rows, key=lambda x: (x.get("question", "~"), x.get("date", ""), x["name"])):
                paths = "<br>".join(f"`{p}`" for p in s["paths"])
                note = s.get("note", "")
                if s.get("superseded_by"):
                    note = (f"Replaced by `{s['superseded_by']}`. " + note).strip()
                if s.get("commits"):
                    note = (note + " Commits: " + ", ".join(f"`{c}`" for c in s["commits"]) + ".").strip()
                cells = [paths, s.get("date", ""), s.get("question", ""), s["purpose"],
                         f"`{s['campaign']}`" if s.get("campaign") else "",
                         f"`{s['location']}`" if s.get("location") else "",
                         note]
                out.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
            out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    sub.add_parser("render")
    ls = sub.add_parser("list")
    ls.add_argument("--paper", choices=PAPERS)
    ls.add_argument("--status", choices=STATUSES)
    args = ap.parse_args(argv)
    papers, sets = load()
    if args.cmd == "check":
        errors = check(papers, sets)
        rendered = render(papers, sets) + "\n"
        if RENDERED.exists() and RENDERED.read_text() != rendered:
            errors.append("experiments/CATALOGUE.md is stale; run scripts/catalogue.py render")
        for e in errors:
            print(e, file=sys.stderr)
        print(f"{len(sets)} sets, {len(errors)} problem(s)")
        return 1 if errors else 0
    if args.cmd == "render":
        RENDERED.write_text(render(papers, sets) + "\n")
        print(f"wrote {RENDERED.relative_to(REPO)}")
        return 0
    for s in sets:
        if args.paper and s["paper"] != args.paper:
            continue
        if args.status and s["status"] != args.status:
            continue
        print(f"{s['paper']:4} {s['status']:11} {s['name']:40} {s.get('question', '')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
